# Aritmética

print(2 + 3) # sumar(+)
print(3 - 1)   # resta(-)
print(2 * 3)   # multiplicación(*)
print(3 / 2)   # división(/)
print(3 ** 2)  # exponencial(**)
print(3 % 2)   # módulo(%)
print(3 // 2)  # División(//)

# Comprobando los tipos

print(type(10)) # Int
print(type(3.14)) # Float
print(type(1 + 3)) # Complejo
print(type('barco-de-codigo-amarillo')) # Cadena o Str
print(type([1, 2, 3])) # Lista: ordenadas y modificables
print(type({'name': 'Lord Byron'})) # Diccionario: guardan pares de clave y valor
print(type({9.8, 3.14, 2.7})) # Conjunto no está ordenado y no se repiten; son 'set' y 'frozenset'
print(type({1, 2, "tres"})) # Tupla: ordenadas pero inmutables